// ── Assembler + Linker ────────────────────────

func AssembleAndLink(cfg *Config, log *Logger) error {
	objFile := cfg.AsmFile + ".o"

	log.Step("as", "as -o "+objFile+" "+cfg.AsmFile)
	if err := runCmd("as", "-o", objFile, cfg.AsmFile); err != nil {
		return fmt.Errorf("assembler failed: %w", err)
	}

	log.Step("ld", "ld -o "+cfg.BinFile+" "+objFile)
	if err := runCmd("ld", "-o", cfg.BinFile, objFile); err != nil {
		return fmt.Errorf("linker failed: %w", err)
	}

	if !cfg.NoCleanup {
		os.Remove(objFile)
	}
	return nil
}

