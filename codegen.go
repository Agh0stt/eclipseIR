func cmpCond(kind InstrKind) string {
	switch kind {
	case INS_CMP_GT:
		return "gt"
	case INS_CMP_LT:
		return "lt"
	case INS_CMP_EQ:
		return "eq"
	case INS_CMP_GE:
		return "ge"
	case INS_CMP_LE:
		return "le"
	case INS_CMP_NE:
		return "ne"
	}
	return "al"
}

func escapeForAs(s string) string {
	var b strings.Builder
	for _, ch := range s {
		switch ch {
		case '"':
			b.WriteString("\\\"")
		case '\\':
			b.WriteString("\\\\")
		case '\n':
			b.WriteString("\\n")
		case '\t':
			b.WriteString("\\t")
		case '\r':
			b.WriteString("\\r")
		case 0:
			b.WriteString("\\0")
		default:
			b.WriteRune(ch)
		}
	}
	return b.String()
}
